#!/usr/bin/env python3
"""Developer tool: reference translations for the Rust Argos translator's parity test.

Runs installed Argos packages with Python CTranslate2 + SentencePiece using the same
settings as argostranslate (beam 4, length penalty 0.2, unknown-token replacement) and
writes src-tauri/tests/fixtures/argos_reference.json.

usage: build/venv/bin/python scripts/bench/argos_reference.py <translation-packages-dir>
       (e.g. build/devhome/data/models/translation)
"""
import json
import sys
from pathlib import Path

import ctranslate2
import sentencepiece

CASES = {
    "en_bn": ["The weather is lovely today, so we are going for a walk by the river.", "Welcome to CaptionNest."],
    "bn_en": ["আজ আবহাওয়া খুব সুন্দর, তাই আমরা নদীর ধারে বেড়াতে যাব।", "আমি বাংলায় কথা বলি।"],
    "en_hi": ["Thank you for watching this video."],
    "en_ar": ["Thank you for watching this video."],
}

root = Path(sys.argv[1])
out = {"note": "Generated by scripts/bench/argos_reference.py with ctranslate2 " + ctranslate2.__version__, "cases": []}
for pkg, inputs in CASES.items():
    d = root / pkg
    if not (d / "model").exists():
        print(f"skip {pkg}: not installed")
        continue
    sp = sentencepiece.SentencePieceProcessor(model_file=str(d / "sentencepiece.model"))
    tr = ctranslate2.Translator(str(d / "model"), device="cpu")
    for text in inputs:
        tokens = sp.encode(text, out_type=str)
        res = tr.translate_batch([tokens], beam_size=4, length_penalty=0.2, replace_unknowns=True)
        translated = "".join(res[0].hypotheses[0]).replace("▁", " ").strip()
        out["cases"].append({"package": pkg, "input": text, "expected": translated})
        print(f"{pkg}: {text} -> {translated}")
dest = Path(__file__).resolve().parents[2] / "src-tauri" / "tests" / "fixtures" / "argos_reference.json"
dest.write_text(json.dumps(out, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
print(f"wrote {dest}")
